"""ORM models: the tables of specification section 6.2, with the rules of section 6.3.

Status, type, length and language columns are VARCHAR with a CHECK constraint (not PostgreSQL ENUM
types): adding a value later is a one-line constraint change instead of an ALTER TYPE migration.
The allowed values live in the StrEnums below, so the application and the database use one list.
"""

