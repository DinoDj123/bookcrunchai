from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    Numeric,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    false,
    func,
    true,
)
from sqlalchemy.dialects.postgresql import CHAR, JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base
from app.parsing import ChapterKind, FileFormat

EMBEDDING_DIMENSIONS = 1024  # BAAI bge-m3, open-source multilingual embeddings (FR-010)


class BookStatus(StrEnum):
    UPLOADED = "uploaded"
    PROCESSING = "processing"
    READY = "ready"
    FAILED = "failed"


class SummaryLength(StrEnum):
    FIVE_MIN = "5min"
    FIFTEEN_MIN = "15min"


class Language(StrEnum):
    EN = "en"
    CNR = "cnr"  # Montenegrin (ISO 639-3)


class SummaryStatus(StrEnum):
    QUEUED = "queued"
    RUNNING = "running"
    READY = "ready"
    FAILED = "failed"


class JobType(StrEnum):
    PROCESS_BOOK = "process_book"
    GENERATE_SUMMARY = "generate_summary"


class JobStatus(StrEnum):
    QUEUED = "queued"
    RUNNING = "running"
    DONE = "done"
    FAILED = "failed"


class JobStage(StrEnum):
    PARSING = "parsing"
    CHUNKING = "chunking"
    EMBEDDING = "embedding"
    CHAPTER_NOTES = "chapter_notes"
    REDUCE = "reduce"


class UsageStep(StrEnum):
    MAP = "map"
    REDUCE = "reduce"
    EMBED = "embed"
    QA = "qa"


def one_of(column: str, values: type[StrEnum]) -> CheckConstraint:
    """CHECK constraint that limits a column to the values of an enum, named "<column>_valid"."""
    allowed = ", ".join(f"'{v.value}'" for v in values)
    return CheckConstraint(f"{column} IN ({allowed})", name=f"{column}_valid")


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUID primary key generated by the application (section 6.2), not by the database."""
    return mapped_column(primary_key=True, default=uuid.uuid4)


def book_fk() -> Mapped[uuid.UUID]:
    """Every derived row is deleted with its book (FR-015, section 6.3)."""
    return mapped_column(ForeignKey("books.id", ondelete="CASCADE"), index=True)


def same_book(column: str, table: str) -> ForeignKeyConstraint:
    """Foreign key (column, book_id) -> table (id, book_id).

    The referenced row must exist AND belong to the same book as this row, so the database itself
    refuses, for example, a key idea that points to a chapter of another book (section 6.3).
    The target table needs UniqueConstraint("id", "book_id"). It cascades like book_fk(): deleting
    a book deletes its chapters, and with them every row that points to those chapters.
    """
    return ForeignKeyConstraint(
        [column, "book_id"], [f"{table}.id", f"{table}.book_id"], ondelete="CASCADE"
    )


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class User(TimestampMixin, Base):
    __tablename__ = "users"
    __table_args__ = (
        # The API lower-cases emails; this stops "Ana@x.com" and "ana@x.com" becoming two accounts
        # if some code path forgets to.
        CheckConstraint("email = lower(email)", name="email_lower_case"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    email: Mapped[str] = mapped_column(String(255), unique=True)
    password_hash: Mapped[str] = mapped_column(String(255))  # Argon2id


class Book(TimestampMixin, Base):
    __tablename__ = "books"
    __table_args__ = (
        UniqueConstraint("owner_id", "file_sha256"),  # one copy of a file per user
        CheckConstraint("file_size_bytes > 0", name="file_size_positive"),
        one_of("file_format", FileFormat),
        one_of("status", BookStatus),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    # No index of its own: the (owner_id, file_sha256) unique index starts with owner_id.
    owner_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))
    title: Mapped[str] = mapped_column(String(500))
    author: Mapped[str | None] = mapped_column(String(300))
    source_language: Mapped[str | None] = mapped_column(String(8))
    file_format: Mapped[str] = mapped_column(String(4))
    file_sha256: Mapped[str] = mapped_column(CHAR(64))
    file_path: Mapped[str] = mapped_column(String(500))
    file_size_bytes: Mapped[int] = mapped_column(BigInteger)
    status: Mapped[str] = mapped_column(String(12))
    error_code: Mapped[str | None] = mapped_column(String(40))
    chapters_detected: Mapped[bool] = mapped_column(Boolean, server_default=true())
    word_count: Mapped[int | None] = mapped_column(Integer)
    is_demo: Mapped[bool] = mapped_column(Boolean, server_default=false())


class Chapter(TimestampMixin, Base):
    __tablename__ = "chapters"
    __table_args__ = (
        UniqueConstraint("book_id", "position"),
        UniqueConstraint("id", "book_id"),  # target of same_book() foreign keys
        one_of("kind", ChapterKind),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    # Not indexed separately: the (book_id, position) unique index covers lookups by book.
    book_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("books.id", ondelete="CASCADE"))
    position: Mapped[int] = mapped_column(Integer)
    title: Mapped[str] = mapped_column(String(500))
    kind: Mapped[str] = mapped_column(String(12))
    word_count: Mapped[int] = mapped_column(Integer)
    notes: Mapped[str | None] = mapped_column(Text)  # chapter notes from the map step (FR-007)


class Chunk(TimestampMixin, Base):
    __tablename__ = "chunks"
    __table_args__ = (
        UniqueConstraint("chapter_id", "position"),
        UniqueConstraint("id", "book_id"),  # target of same_book() foreign keys
        same_book("chapter_id", "chapters"),
        Index(
            "ix_chunks_embedding",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    book_id: Mapped[uuid.UUID] = book_fk()  # retrieval filters chunks by book (FR-010)
    chapter_id: Mapped[uuid.UUID] = mapped_column()
    position: Mapped[int] = mapped_column(Integer)
    text: Mapped[str] = mapped_column(Text)
    token_count: Mapped[int] = mapped_column(Integer)
    page_start: Mapped[int | None] = mapped_column(Integer)  # PDF only
    # Read back as a numpy array by pgvector.
    embedding: Mapped[list[float] | None] = mapped_column(Vector(EMBEDDING_DIMENSIONS))


class Summary(TimestampMixin, Base):
    __tablename__ = "summaries"
    __table_args__ = (
        # The cache key (FR-014): one summary per book, length and language.
        UniqueConstraint("book_id", "length", "language"),
        UniqueConstraint("id", "book_id"),  # target of same_book() foreign keys
        one_of("length", SummaryLength),
        one_of("language", Language),
        one_of("status", SummaryStatus),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    # Not indexed separately: the unique index above starts with book_id.
    book_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("books.id", ondelete="CASCADE"))
    length: Mapped[str] = mapped_column(String(8))
    language: Mapped[str] = mapped_column(String(8))
    status: Mapped[str] = mapped_column(String(12))
    overview: Mapped[str | None] = mapped_column(Text)
    word_count: Mapped[int | None] = mapped_column(Integer)
    model: Mapped[str | None] = mapped_column(String(60))


class ChapterSummary(TimestampMixin, Base):
    __tablename__ = "chapter_summaries"
    __table_args__ = (
        same_book("summary_id", "summaries"),
        same_book("chapter_id", "chapters"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    # Only used to tie the summary and the chapter to one book; see same_book().
    book_id: Mapped[uuid.UUID] = mapped_column()
    summary_id: Mapped[uuid.UUID] = mapped_column(index=True)
    chapter_id: Mapped[uuid.UUID] = mapped_column(index=True)
    content: Mapped[str] = mapped_column(Text)


class KeyIdea(TimestampMixin, Base):
    __tablename__ = "key_ideas"
    __table_args__ = (
        same_book("summary_id", "summaries"),
        same_book("chapter_id", "chapters"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    book_id: Mapped[uuid.UUID] = mapped_column()  # see same_book()
    summary_id: Mapped[uuid.UUID] = mapped_column(index=True)
    chapter_id: Mapped[uuid.UUID] = mapped_column(index=True)
    position: Mapped[int] = mapped_column(Integer)
    text: Mapped[str] = mapped_column(Text)


class Question(TimestampMixin, Base):
    __tablename__ = "questions"
    __table_args__ = (
        UniqueConstraint("id", "book_id"),  # target of same_book() foreign keys
        one_of("language", Language),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    book_id: Mapped[uuid.UUID] = book_fk()
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    question: Mapped[str] = mapped_column(String(500))  # 1-500 chars after trimming (API checks)
    answer: Mapped[str] = mapped_column(Text)
    language: Mapped[str] = mapped_column(String(8))
    answerable: Mapped[bool] = mapped_column(Boolean)


class Citation(TimestampMixin, Base):
    __tablename__ = "citations"
    __table_args__ = (
        # An answer can only cite passages of the book it is about; a mix-up would show a
        # passage of another user's book (FR-015).
        same_book("question_id", "questions"),
        same_book("chunk_id", "chunks"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    book_id: Mapped[uuid.UUID] = mapped_column()  # see same_book()
    question_id: Mapped[uuid.UUID] = mapped_column(index=True)
    chunk_id: Mapped[uuid.UUID] = mapped_column(index=True)
    position: Mapped[int] = mapped_column(Integer)
    quote: Mapped[str] = mapped_column(Text)  # stored only if found in the chunk (section 6.3)


class Job(TimestampMixin, Base):
    __tablename__ = "jobs"
    __table_args__ = (
        one_of("type", JobType),
        one_of("status", JobStatus),
        one_of("stage", JobStage),  # NULL passes a CHECK constraint, so stage stays optional
        CheckConstraint("progress BETWEEN 0 AND 100", name="progress_range"),
        CheckConstraint("attempts >= 0", name="attempts_non_negative"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    book_id: Mapped[uuid.UUID] = book_fk()
    type: Mapped[str] = mapped_column(String(24))
    status: Mapped[str] = mapped_column(String(12))
    stage: Mapped[str | None] = mapped_column(String(24))
    progress: Mapped[int] = mapped_column(SmallInteger, server_default="0")
    params: Mapped[dict[str, Any] | None] = mapped_column(JSONB)  # e.g. length and language
    error_code: Mapped[str | None] = mapped_column(String(40))
    error_message: Mapped[str | None] = mapped_column(Text)
    attempts: Mapped[int] = mapped_column(SmallInteger, server_default="0")
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class LlmUsage(TimestampMixin, Base):
    __tablename__ = "llm_usage"
    __table_args__ = (
        one_of("step", UsageStep),
        CheckConstraint("input_tokens >= 0", name="input_tokens_non_negative"),
        CheckConstraint("output_tokens >= 0", name="output_tokens_non_negative"),
        CheckConstraint("cost_usd >= 0", name="cost_usd_non_negative"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    book_id: Mapped[uuid.UUID] = book_fk()
    # SET NULL: a usage record (money already spent) outlives the job that made the call.
    job_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("jobs.id", ondelete="SET NULL"), index=True
    )
    step: Mapped[str] = mapped_column(String(16))
    model: Mapped[str] = mapped_column(String(60))
    input_tokens: Mapped[int] = mapped_column(Integer)
    output_tokens: Mapped[int] = mapped_column(Integer)
    cost_usd: Mapped[Decimal] = mapped_column(Numeric(10, 6))
